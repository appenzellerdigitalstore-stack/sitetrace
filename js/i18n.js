  // ---- Public state ----------------------------------------------
  let currentLang = 'en';
  const listeners = [];

  // ---- Helpers ----------------------------------------------------
  function detectLanguage() {
    const supported = Object.keys(dictionaries);
    // sessionStorage is per-tab and cleared when the tab closes — so the
    // user's manual language choice persists for the session but does not
    // track them across visits. localStorage would persist forever, which
    // we explicitly don't want.
    try {
      const saved = sessionStorage.getItem('sitetrace.lang');
      if (saved && supported.includes(saved)) return saved;
    } catch (_) { /* storage may be blocked */ }
    const candidates = [];
    if (Array.isArray(navigator.languages)) candidates.push(...navigator.languages);
    if (navigator.language) candidates.push(navigator.language);
    for (const raw of candidates) {
      if (!raw) continue;
      const tag = raw.toLowerCase().split('-')[0];
      if (supported.includes(tag)) return tag;
    }
    return 'en';
  }

  function get(obj, path, fallback) {
    return obj && obj[path] != null ? obj[path] : (fallback != null ? fallback : path);
  }

  function t(key) {
    return get(dictionaries[currentLang], key, get(dictionaries.en, key, key));
  }

  function applyTranslations(root) {
    root = root || document;
    const nodes = root.querySelectorAll('[data-i18n]');
    nodes.forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    const attrNodes = root.querySelectorAll('[data-i18n-attr]');
    attrNodes.forEach((el) => {
      const spec = el.getAttribute('data-i18n-attr');
      spec.split(';').forEach((pair) => {
        const [attr, key] = pair.split(':').map((s) => s && s.trim());
        if (attr && key) el.setAttribute(attr, t(key));
      });
    });
    document.documentElement.setAttribute('lang', currentLang);
    listeners.forEach((cb) => { try { cb(currentLang); } catch (_) {} });
  }

  function setLanguage(lang, options) {
    if (!dictionaries[lang]) lang = 'en';
    currentLang = lang;
    if (!options || !options.skipPersist) {
      try { sessionStorage.setItem('sitetrace.lang', lang); } catch (_) {}
    }
    applyTranslations();
    return currentLang;
  }

  function onChange(cb) { listeners.push(cb); }

  // ---- Public API -------------------------------------------------
  global.I18N = {
    t,
    setLanguage,
    getLanguage: () => currentLang,
    getSupported: () => Object.keys(dictionaries),
    onChange,
    applyTranslations,
    detectLanguage,
    dictionaries,
  };

  // Auto-init: use sessionStorage (not localStorage) so it doesn't persist
  function init() {
    const lang = detectLanguage();
    setLanguage(lang, { skipPersist: true });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init, { once: true });
  } else {
    init();
  }
