// scripts/generate-redirects.mjs
// Parses the root _redirects file and emits src/generated/redirects.ts.
//
// Why this exists: this site builds to a Cloudflare Pages `_worker.js`.
// Cloudflare hands every request to that worker and does not consult the
// `_redirects` file, so rules that live only in _redirects never run. The same
// rules are therefore compiled into a TypeScript module the worker imports,
// and applied by src/lib/legacy-redirect.ts before the router.
//
// Parsing _redirects (rather than declaring the rules twice) keeps the two in
// sync. If you add a rule there, run this script.
//
// Run: node scripts/generate-redirects.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const raw = readFileSync(resolve(ROOT, "_redirects"), "utf8");

const exact = new Map();
const wildcards = [];

for (const line of raw.split("\n")) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith("#")) continue;

  const parts = trimmed.split(/\s+/);
  if (parts.length < 2) continue;

  const [from, to] = parts;
  if (from.includes("*")) wildcards.push([from, to]);
  else exact.set(from, to);
}

// A rule that points at itself would loop forever at the edge.
for (const [from, to] of exact) {
  if (from === to) throw new Error(`self-referencing redirect: ${from} -> ${to}`);
}

// Every destination must itself be canonical (no trailing slash), otherwise the
// browser takes a second hop and the 301 chain is not clean.
for (const [from, to] of [...exact, ...wildcards]) {
  if (to.length > 1 && to.endsWith("/") && !to.includes("*")) {
    throw new Error(`non-canonical destination: ${from} -> ${to}`);
  }
}

const tsLines = [
  "// AUTO-GENERATED by scripts/generate-redirects.mjs - do not edit by hand.",
  "//",
  "// Legacy URL map applied at the edge by src/lib/legacy-redirect.ts.",
  "// Parsed from the root _redirects file. The worker reads this module because",
  "// a Cloudflare Pages `_worker.js` build bypasses `_redirects` entirely.",
  "",
  "export const EXACT_REDIRECTS: Record<string, string> = {",
  ...[...exact.entries()].map(([from, to]) => `  ${JSON.stringify(from)}: ${JSON.stringify(to)},`),
  "};",
  "",
  "/** Patterns containing `*`; the captured segment is substituted into the target. */",
  "export const WILDCARD_REDIRECTS: Array<[string, string]> = [",
  ...wildcards.map(([from, to]) => `  [${JSON.stringify(from)}, ${JSON.stringify(to)}],`),
  "];",
  "",
];

const out = resolve(ROOT, "src", "generated", "redirects.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, tsLines.join("\n"), "utf8");

console.log(
  `OK: wrote ${exact.size} exact + ${wildcards.length} wildcard rules to ${out}`,
);